const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const m = new Module('ict-chart-context');
m._compile(ts.transpileModule(fs.readFileSync('src/lib/ict-chart-context.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, 'ict-chart-context.cjs');
const { ictChartContext } = m.exports;
const bar = (time, open, high, low, close) => ({ time, open, high, low, close });
const bars = [bar(0, 10, 12, 9, 11), bar(60, 12, 15, 11, 14), bar(120, 14, 16, 13, 15), bar(180, 14, 15, 10, 11)];
const zones = ictChartContext(bars, 60, 'UTC');
assert.equal(zones.find(z => z.kind === 'vi').time, 120);
const bisi = zones.find(z => z.kind === 'fvg');
assert.equal(bisi.time, 180);
assert.equal(bisi.low, 12);
assert.equal(bisi.high, 13);
assert.equal(bisi.end_time, 180);
assert.equal(ictChartContext(bars.slice(0, 2), 60, 'UTC').some(z => z.kind === 'fvg'), false);
assert.equal(ictChartContext([bars[0], {...bars[1], time: 120}], 60, 'UTC').some(z => z.kind === 'vi'), false);
const swing = [bar(0, 4, 5, 3, 4), bar(60, 5, 6, 4, 5), bar(120, 6, 9, 5, 6), bar(180, 5, 7, 4, 5), bar(240, 4, 6, 3, 4)];
assert.equal(ictChartContext(swing.slice(0, 4), 60, 'UTC').some(z => z.kind === 'bsl'), false);
assert.equal(ictChartContext(swing, 60, 'UTC').find(z => z.kind === 'bsl').time, 300);
const days = Array.from({length: 4}, (_, i) => bar(Date.UTC(2026, 9, 5+i, 14)/1000, 10+i, 12+i, 9+i, 11+i));
const periods = ictChartContext(days, 300, 'America/New_York').filter(z => z.kind === 'period');
assert.equal(periods.length, 4);
assert.equal(periods[0].time, days[2].time);
assert.equal(periods[0].low, days[1].high);
assert.equal(periods.some(z => z.label.startsWith('PWL')), false);
const compile = (file) => {
  const mod = new Module(file);
  mod._compile(ts.transpileModule(fs.readFileSync(`src/lib/${file}.ts`, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText, `${file}.cjs`);
  return mod.exports;
};
const sweep = compile('liquidity-sweeps');
const replay = new Module('weekly-replay');
replay.require = id => { if (id === './liquidity-sweeps') return sweep; throw Error(id); };
replay._compile(ts.transpileModule(fs.readFileSync('src/lib/weekly-replay.ts', 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText, 'weekly-replay.cjs');
const replayBars = bars.map(b => ({t:b.time*1000,knownAt:(b.time+60)*1000,day:'2026-10-05',minute:570+b.time/60,o:b.open,h:b.high,l:b.low,c:b.close}));
const vi = replay.exports.deriveIctOverlays(replayBars.slice(0,2),'1m','us',[]).find(z=>z.kind==='VI');
assert.ok(vi);
assert.equal(vi.knownAt,120000);
assert.equal(vi.touches,0);
assert.equal(replay.exports.deriveIctOverlays([replayBars[0],{...replayBars[1],day:'2026-10-06'}],'1m','us',[]).some(z=>z.kind==='VI'),false);
console.log('PASS: completed-candle VI/FVG confirmation, gap exclusion, swing confirmation, fill timing and period withholding.');

