const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const m = new Module('pd-arrays');
m._compile(ts.transpileModule(fs.readFileSync('src/lib/pd-arrays.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText, 'pd-arrays.cjs');
const { pdArrays } = m.exports;
const range = {h:120,l:80,knownAt:10,day:'2026-01-05'};
const zone = (id,kind,direction,low,high,knownAt=11,status='ACTIVE') => ({id,kind,direction,low,high,knownAt,status,originDay:'2026-01-06'});
const zones = [zone('sell','OB','SELL',105,110),zone('buy','FVG','BUY',85,95),zone('future','BREAKER','SELL',110,115,21),zone('cross','FVG','BUY',95,105),zone('outside','OB','BUY',60,70),zone('wrong','OB','SELL',85,90),zone('swept','BREAKER','BUY',85,90,11,'SWEPT')];
const result = pdArrays(range,20,zones,[]);
assert.equal(result.midpoint,100);
assert.deepEqual(result.premium.map(r=>r.label),['Old High / Low','Rejection Block','Bearish Orderblock','Fair Value Gap','Liquidity Void','Bearish Breaker','Mitigation Block']);
assert.deepEqual(result.discount.map(r=>r.label),['Mitigation Block','Bullish Breaker','Liquidity Void','Fair Value Gap','Bullish Orderblock','Rejection Block','Old Low / High']);
assert.deepEqual(result.premium.flatMap(r=>r.levels.map(l=>l.id)),['range-SELL','sell']);
assert.deepEqual(result.discount.flatMap(r=>r.levels.map(l=>l.id)),['buy','range-BUY']);
assert.equal(result.straddling,1);
assert.equal(pdArrays(range,9,zones,[]),null);
assert.equal(pdArrays({...range,h:80},20,zones,[]),null);
const futureWick = {id:'wick',direction:'BUY',low:85,high:90,knownAt:21,status:'ACTIVE'};
assert.equal(pdArrays(range,20,[],[],[futureWick]).discount.find(r=>r.label==='Rejection Block').levels.length,0);
console.log('PASS: exact PD hierarchy, equilibrium, direction and range eligibility, future/swept exclusion, straddlers and missing-range withholding.');
