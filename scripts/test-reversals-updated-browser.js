async page => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const root = page.getByTestId('reversals-updated');
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.goto('http://localhost:3000/?tab=reversals-updated');
  await root.getByRole('heading', { name: 'Reversals updated', exact: true }).waitFor();
  await root.getByRole('heading', { name: 'Trade & decision ledger' }).waitFor({ timeout: 90000 });
  if (!(await root.innerText()).includes('3,427') && !(await root.innerText()).includes('3427')) throw new Error('Full-history metrics not rendered');
  await page.screenshot({ path: 'output/playwright/reversals-updated/desktop.png' });
  await root.getByRole('button', { name: 'Strategy walkthrough', exact: true }).click();
  await root.getByRole('heading', { name: 'From failed breakout to recorded outcome' }).waitFor();
  await root.getByRole('button', { name: 'Validation & contracts', exact: true }).click();
  await root.getByRole('heading', { name: 'Execution contracts', exact: true }).waitFor();
  await root.getByRole('button', { name: 'Results & trades', exact: true }).click();
  await root.getByRole('button', { name: /^Inspect / }).first().click();
  const dialog = page.getByRole('dialog', { name: 'Selected reversal evidence' });
  await dialog.waitFor();
  const chartResponse = await page.waitForResponse(r => r.url().includes('/api/reversal/order-chart') && r.url().includes('run='), { timeout: 90000 });
  const chart = await chartResponse.json();
  if (!chartResponse.ok() || !chart.success || !chart.candles?.length) throw new Error(`History chart failed: ${chart.error}`);
  await page.screenshot({ path: 'output/playwright/reversals-updated/history-evidence.png' });
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'detached' });
  await root.getByRole('button', { name: 'OANDA practice', exact: false }).click();
  await root.getByRole('heading', { name: 'Trade & decision ledger' }).waitFor({ timeout: 90000 });
  await root.getByLabel('Reversal timeframe', { exact: true }).selectOption('30m');
  await root.getByRole('button', { name: 'Apply filters', exact: true }).click();
  await root.getByRole('button', { name: /^Inspect / }).first().waitFor({ timeout: 90000 });
  await root.getByRole('button', { name: /^Inspect / }).first().click();
  await dialog.waitFor();
  if (!(await dialog.innerText()).includes('OANDA_PRACTICE_MARKET')) throw new Error('Wrong practice contract');
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await root.scrollIntoViewIfNeeded();
  const dimensions = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }));
  if (dimensions.scroll > dimensions.width + 1) throw new Error(`Mobile overflow: ${JSON.stringify(dimensions)}`);
  await page.screenshot({ path: 'output/playwright/reversals-updated/mobile.png' });
  await root.getByRole('button', { name: 'Paper replay', exact: false }).click();
  await root.getByRole('heading', { name: 'Trade & decision ledger' }).waitFor({ timeout: 90000 });
  await root.getByRole('button', { name: /^Inspect / }).first().click();
  await dialog.waitFor();
  if (!(await dialog.innerText()).includes('Not recorded separately')) throw new Error('Missing clock uncertainty');
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 1440, height: 1080 });
  if (errors.length) throw new Error(errors.join('\n'));
  return { result: 'PASS', chartCandles: chart.candles.length, mobile: dimensions, pageErrors: errors, checks: ['deep link','full-history metrics','walkthrough','validation','run-bound chart','modal keyboard dismissal','practice contract','paper evidence','mobile overflow'] };
}
