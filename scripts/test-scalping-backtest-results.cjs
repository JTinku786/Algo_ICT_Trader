const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const filename = path.resolve('src/lib/scalping-backtest-results.ts');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } });
const m = new Module(filename, module); m.filename = filename; m.paths = module.paths; m._compile(compiled.outputText, filename);
const { createBacktestAggregation, normalizeBacktestTrade } = m.exports;
const filters = { markets: [], symbols: [], years: [], buckets: [], side: 'ALL', confirmation: 'ALL', page: 1 };
const at = Date.parse('2023-12-01T10:00:00Z');
const row = { id: '1', symbol: 'AAPL', market: 'us', entryAt: at, exitAt: at + 300000, side: 'BUY', tf1Kind: 'OB', tf2Kind: 'FVG', confirmation: 'CHOCH', rrBucket: '1-2', plannedRR: 1.5, result: 'WIN', r: 1.5, entry: 100, stop: 99, target: 101.5 };
const agg = createBacktestAggregation(filters);
agg.consume(row);
agg.consume({ ...row, id: '2', rrBucket: '2-3', plannedRR: 2.5, result: 'OPEN', r: 30, exitAt: null });
agg.consume({ ...row, id: '3', result: 'LOSS', r: -1, entryAt: at + 300000, exitAt: at + 600000 });
const result = agg.result();
assert.equal(result.stats.scenarios, 3); assert.equal(result.stats.closed, 2); assert.equal(result.stats.open, 1);
assert.equal(result.stats.grossR, 0.5); assert.equal(result.stats.expectancy, 0.25); assert.equal(result.stats.profitFactor, 1.5);
assert.equal(result.buckets.find(x => x.bucket === '2-3').grossR, 0);
assert.equal(result.combinations[0].train.closed, 2);
assert.equal(result.equity.at(-1).cumulativeR, 0.5);
assert.equal(normalizeBacktestTrade({ ...row, entryAt: at / 1000 }).entryAt, at);
const crossed = createBacktestAggregation(filters);
crossed.consume({ ...row, exitAt: Date.parse('2024-01-01T10:00:00Z') });
assert.equal(crossed.result().combinations[0].train.closed, 0, 'An exit not known by training cutoff must not affect training');
const attrs = createBacktestAggregation({ ...filters, confirmation: 'CISD' });
attrs.consume({ ...row, attributions: [{ tf1Kind: 'OB', tf2Kind: 'VALID_FVG', confirmation: 'CISD' }, { tf1Kind: 'OB', tf2Kind: 'VALID_FVG', confirmation: 'CISD' }, { tf1Kind: 'BPR', tf2Kind: 'OB', confirmation: 'CHOCH' }] });
assert.equal(attrs.result().stats.closed, 1, 'Economic entry counts once, even with several attributions');
assert.equal(attrs.result().combinations.length, 1); assert.equal(attrs.result().combinations[0].confirmation, 'CISD');
const both = createBacktestAggregation(filters);
both.consume({ ...row, attributions: [{ tf1Kind: 'OB', tf2Kind: 'VALID_FVG', confirmation: 'CHOCH' }, { tf1Kind: 'OB', tf2Kind: 'VALID_FVG', confirmation: 'CISD' }] });
assert.equal(both.result().combinations.length, 2); assert.equal(both.result().heatmapCells.length, 1); assert.equal(both.result().heatmapCells[0].closed, 1);
const held = createBacktestAggregation(filters);
held.consume({ ...row, entryAt: Date.parse('2024-01-02T10:00:00Z'), exitAt: Date.parse('2024-01-02T10:05:00Z') });
assert.equal(held.result().combinations[0].holdout.closed, 1);
const filtered = createBacktestAggregation({ ...filters, markets: ['forex'] }); filtered.consume(row); assert.equal(filtered.result().stats.closed, 0);
const pages = createBacktestAggregation({ ...filters, page: 2 });
for (let i = 0; i < 120; i++) pages.consume({ ...row, id: String(i), entryAt: at + i * 300000 });
assert.equal(pages.result().trades.length, 50); assert.equal(pages.result().trades[0].id, '69'); assert.equal(pages.result().trades.at(-1).id, '20');
console.log('PASS: closed/open metrics, independent buckets, causal training cutoff, attribution dedup, filters, millisecond clocks and descending pagination.');

const pairFiltered = createBacktestAggregation({ ...filters, tf1: 'PDL', tf2: 'OB' });
pairFiltered.consume({ ...row, id: 'wrong-pair', attributions: [{ tf1Kind: 'PDL', tf2Kind: 'BPR', confirmation: 'CHOCH' }, { tf1Kind: 'BPR', tf2Kind: 'OB', confirmation: 'CHOCH' }] });
pairFiltered.consume({ ...row, id: 'right-pair', attributions: [{ tf1Kind: 'PDL', tf2Kind: 'OB', confirmation: 'CHOCH' }] });
assert.equal(pairFiltered.result().pagination.total, 1);
assert.equal(pairFiltered.result().trades[0].id, 'right-pair');
assert.equal(pairFiltered.result().stats.scenarios, 1, 'Pair filters must apply to analytics and trades together');
console.log('PASS: joint attribution filter excludes unrelated pairs in both analytics and trades.');

const axp = createBacktestAggregation({...filters, symbols: ['AXP'], buckets: ['1-2','2-3','3-4','4+'], tf1: 'PDL', tf2: 'OB', confirmation: 'CISD'});
const axpRow = {...row, symbol:'AXP', attributions:[{tf1Kind:'PDL',tf2Kind:'OB',confirmation:'CISD',contextId:'axp-context',arrayId:'axp-array'},{tf1Kind:'BPR',tf2Kind:'OB',confirmation:'CHOCH'}]};
axp.consume(axpRow);
axp.consume({...axpRow,id:'low-rr',rrBucket:'0-1'});
axp.consume({...axpRow,id:'other-ticker',symbol:'AAPL'});
axp.consume({...axpRow,id:'crossed-confirmation',attributions:[{tf1Kind:'PDL',tf2Kind:'OB',confirmation:'CHOCH'},{tf1Kind:'BPR',tf2Kind:'OB',confirmation:'CISD'}]});
const axpResults=axp.result();
assert.equal(axpResults.stats.scenarios,1);assert.equal(axpResults.pagination.total,1);
assert.equal(axpResults.stats.grossR,1.5);assert.equal(axpResults.combinations.length,1);
assert.equal(axpResults.heatmapCells.length,1);assert.equal(axpResults.buckets.length,1);
assert.equal(axpResults.years.length,1);assert.equal(axpResults.equity.at(-1).cumulativeR,1.5);
assert.equal(axpResults.costSensitivity[0].closed,1);
assert.equal(axpResults.trades[0].attributions[0].contextId,'axp-context');
console.log('PASS: AXP excluding 0-1 reconciles metrics, exact joint setup/confirmation, source IDs, buckets, annual outcomes, equity and costs.');
